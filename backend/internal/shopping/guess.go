package shopping

import (
	"strings"
	"unicode"
)

// guessCategoryKey suggests a built-in category for a new product by its
// name, e.g. "Молоко 3,2%" -> "dairy". It's a deliberately simple keyword
// matcher: once a product exists, its category is remembered, so a wrong
// guess is fixed once by hand and never again.
//
// Matching rules:
//  1. Phrases (stems containing a space, like "для посуд") are checked first
//     as substrings: they are the most specific signal. Only the LAST word of
//     a phrase may be truncated ("для посуд" matches "для посуды", but
//     "туалетн бумаг" would never match "туалетная бумага").
//  2. Then single stems are matched as word prefixes, in guessOrder: non-food
//     categories go first, so "зубная паста" is hygiene, not pasta.
//  3. No match means "other": every new product gets some category.
func guessCategoryKey(name string) string {
	text := normalizeForGuess(name)
	words := strings.FieldsFunc(text, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })

	for _, key := range guessOrder {
		for _, stem := range categoryStems[key] {
			if strings.Contains(stem, " ") && strings.Contains(text, stem) {
				return key
			}
		}
	}
	for _, key := range guessOrder {
		for _, stem := range categoryStems[key] {
			if strings.Contains(stem, " ") {
				continue
			}
			for _, w := range words {
				if strings.HasPrefix(w, stem) {
					return key
				}
			}
		}
	}
	return "other"
}

func normalizeForGuess(s string) string {
	return strings.ReplaceAll(strings.ToLower(s), "ё", "е")
}

