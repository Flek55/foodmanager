-- Shopping list: categories, stores, the household's product catalog and
-- list items.
--
-- Conventions for all household data (they enable offline sync in stage 3):
--   * version    = households.version at the moment of the last write;
--   * deleted_at = soft delete (a tombstone), so clients learn about deletions;
--   * composite FKs (household_id, x_id) make it impossible, at the DB level,
--     for one family's rows to reference another family's rows.

-- +goose Up
CREATE TABLE categories (
    id           uuid PRIMARY KEY DEFAULT uuidv7(),
    household_id uuid        NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    -- Stable key of a built-in category ("dairy"), used to auto-categorize
    -- new products. NULL for categories a family created itself.
    key          text,
    name         text        NOT NULL,
    emoji        text,
    sort_order   int         NOT NULL DEFAULT 0,
    version      bigint      NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    deleted_at   timestamptz,
    UNIQUE (household_id, id)
);
CREATE INDEX categories_household_version_idx ON categories (household_id, version);
CREATE UNIQUE INDEX categories_key_idx ON categories (household_id, key)
    WHERE key IS NOT NULL AND deleted_at IS NULL;

CREATE TABLE stores (
    id           uuid PRIMARY KEY DEFAULT uuidv7(),
    household_id uuid        NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    name         text        NOT NULL,
    sort_order   int         NOT NULL DEFAULT 0,
    version      bigint      NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    deleted_at   timestamptz,
    UNIQUE (household_id, id)
);
CREATE INDEX stores_household_version_idx ON stores (household_id, version);

-- The family's own product catalog: what they buy, with remembered
-- category, store and unit. Barcodes join here in stage 7.
CREATE TABLE products (
    id               uuid PRIMARY KEY DEFAULT uuidv7(),
    household_id     uuid        NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    name             text        NOT NULL,
    description      text,
    category_id      uuid,
    default_store_id uuid,
    default_unit     text CHECK (default_unit IN ('pcs', 'kg', 'g', 'l', 'ml', 'pack')),
    use_count        int         NOT NULL DEFAULT 0,
    version          bigint      NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    deleted_at       timestamptz,
    UNIQUE (household_id, id),
    FOREIGN KEY (household_id, category_id) REFERENCES categories (household_id, id),
    FOREIGN KEY (household_id, default_store_id) REFERENCES stores (household_id, id)
);
CREATE INDEX products_household_version_idx ON products (household_id, version);
-- One live product per name within a family ("Молоко" == "молоко").
CREATE UNIQUE INDEX products_name_idx ON products (household_id, lower(name)) WHERE deleted_at IS NULL;

CREATE TABLE list_items (
    -- No default: the id may be generated by the client (offline creation).
    id           uuid PRIMARY KEY,
    household_id uuid        NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    product_id   uuid        NOT NULL,
    quantity     double precision CHECK (quantity > 0),
    unit         text CHECK (unit IN ('pcs', 'kg', 'g', 'l', 'ml', 'pack')),
    note         text,
    store_id     uuid,
    added_by     uuid        REFERENCES users (id) ON DELETE SET NULL,
    checked_at   timestamptz,
    checked_by   uuid        REFERENCES users (id) ON DELETE SET NULL,
    version      bigint      NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    deleted_at   timestamptz,
    FOREIGN KEY (household_id, product_id) REFERENCES products (household_id, id),
    FOREIGN KEY (household_id, store_id) REFERENCES stores (household_id, id)
);
CREATE INDEX list_items_household_version_idx ON list_items (household_id, version);
-- A product is on the list at most once while not yet bought.
CREATE UNIQUE INDEX list_items_active_product_idx ON list_items (product_id)
    WHERE checked_at IS NULL AND deleted_at IS NULL;

